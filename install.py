"""Set up Claude in Firefox.

- creates a shared token (server/config.json + extension/config.js)
- registers the MCP server 'claude-in-firefox' in ~/.claude.json (user scope)
- builds dist/claude-in-firefox.zip (for signing on addons.mozilla.org)

Run again any time; the existing token is kept unless --new-token is given.
"""
import json
import os
import secrets
import shutil
import sys
import time
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
SERVER_CFG = os.path.join(HERE, "server", "config.json")
EXT_DIR = os.path.join(HERE, "extension")
EXT_CFG = os.path.join(EXT_DIR, "config.js")
PORT = 18765


def main():
    new = "--new-token" in sys.argv
    if os.path.exists(SERVER_CFG) and not new:
        cfg = json.load(open(SERVER_CFG, encoding="utf-8"))
    else:
        cfg = {"port": PORT, "token": secrets.token_urlsafe(32)}
        json.dump(cfg, open(SERVER_CFG, "w", encoding="utf-8"), indent=2)
    with open(EXT_CFG, "w", encoding="utf-8") as f:
        f.write("// generated by install.py - must match server/config.json\n")
        f.write(f"const BRIDGE = {json.dumps({'port': cfg['port'], 'token': cfg['token']})};\n")
    print(f"bridge port {cfg['port']}")
    print("token for the extension's settings page (click the toolbar icon, paste, Save):")
    print("   ", cfg["token"])

    if "--no-register" not in sys.argv:
        cj = os.path.join(os.path.expanduser("~"), ".claude.json")
        if os.path.exists(cj):
            shutil.copy2(cj, cj + f".bak-firefox-{time.strftime('%Y%m%d-%H%M%S')}")
            data = json.load(open(cj, encoding="utf-8"))
        else:
            data = {}
        data.setdefault("mcpServers", {})["claude-in-firefox"] = {
            "type": "stdio",
            "command": sys.executable,
            "args": [os.path.join(HERE, "server", "firefox_mcp.py")],
            "env": {},
        }
        tmp = cj + ".tmp-firefox"
        json.dump(data, open(tmp, "w", encoding="utf-8"), indent=2, ensure_ascii=False)
        os.replace(tmp, cj)
        print("registered MCP server 'claude-in-firefox' in", cj)

    os.makedirs(os.path.join(HERE, "dist"), exist_ok=True)
    zpath = os.path.join(HERE, "dist", "local-browser-bridge-dev.zip")   # contains your token: never share
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for name in sorted(os.listdir(EXT_DIR)):
            z.write(os.path.join(EXT_DIR, name), name)
    print("built", zpath)


if __name__ == "__main__":
    main()
